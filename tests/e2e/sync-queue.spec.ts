import {test,expect} from '@playwright/test';
const root='http://127.0.0.1:4180';
test('SQLite 待提交队列：同步失败刷新恢复，重试后确认清理；不使用浏览器业务持久化',async({page})=>{
 const suffix=Date.now();const registration=await page.request.post(root+'/api/cloud/register',{data:{email:`queue-${suffix}@example.com`,name:'队列测试',password:'queue-password-12345'}});expect(registration.ok()).toBe(true);
 await page.addInitScript(()=>{indexedDB.open=()=>{throw new Error('禁止浏览器持久化');};Storage.prototype.setItem=()=>{throw new Error('禁止浏览器持久化');};});
 await page.goto(root);await expect(page.getByRole('button',{name:'新建文件',exact:true}).first()).toBeVisible();
 const response=await page.request.post(root+'/api/cloud/workspaces',{data:{name:'持久队列测试'}});const space=await response.json();
 await page.reload();await page.getByLabel('当前工作区',{exact:true}).selectOption(space.id);
 await page.getByRole('button',{name:'新建文件',exact:true}).first().click();await page.getByLabel('文档标题',{exact:true}).fill('队列恢复文档');
 const body=page.getByRole('textbox',{name:'文档正文'});await body.fill('远端初始正文');
 await expect(page.locator('.save-status').filter({hasText:'正在保存'})).toHaveCount(0);
 await page.route('**/api/cloud/document?**',async route=>{if(route.request().method()==='POST')await route.fulfill({status:503,json:{error:'测试同步中断'}});else await route.continue();});
 await body.fill('同步失败后必须落盘的正文');
 await expect(page.locator('.save-status').filter({hasText:'正在保存'})).toHaveCount(0);
 await expect(page.locator('.save-status').first()).toContainText(/已落盘待提交 [1-9]/);
 await page.reload();await expect(body).toContainText('同步失败后必须落盘的正文');
 await expect(page.locator('.save-status').first()).toContainText(/已落盘待提交 [1-9]/);
 await page.unroute('**/api/cloud/document?**');await page.getByRole('button',{name:'重试保存',exact:true}).first().click();
 await expect(page.locator('.save-status').first()).toContainText('已落盘待提交 0 条');
 await expect(page.locator('.save-status').first()).toContainText('最后确认');
 await page.reload();await expect(body).toContainText('同步失败后必须落盘的正文');
 await page.setViewportSize({width:390,height:844});expect(await page.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth)).toBe(true);
 await page.screenshot({path:(process.env.PI_SCRATCH_DIR??'artifacts')+'/sync-queue-mobile.png'});
 await page.setViewportSize({width:1280,height:720});
 await page.route('**/api/cloud/document?**',async route=>{if(route.request().method()==='POST')await route.fulfill({status:503,json:{error:'测试同步中断'}});else await route.continue();});
 await body.fill('空间删除后从暂存草稿恢复的新副本');await expect(page.locator('.save-status').filter({hasText:'正在保存'})).toHaveCount(0);
 const removed=await page.request.delete(root+'/api/cloud/workspace?workspace='+space.id);expect(removed.ok()).toBe(true);
 await page.reload();await expect(page.getByLabel('当前工作区',{exact:true})).not.toContainText('持久队列测试');
 await page.getByLabel('工作区选项',{exact:true}).click();await page.getByRole('button',{name:'从草稿恢复',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'从草稿恢复'});await dialog.getByRole('button',{name:'读取暂存草稿'}).click();
 await expect(dialog.getByLabel('草稿恢复预览')).toContainText('空间删除后从暂存草稿恢复的新副本');
 await dialog.getByRole('button',{name:'恢复为新文档'}).click();await expect(dialog.getByLabel('草稿恢复结果')).toContainText('队列恢复文档');
 await dialog.getByRole('button',{name:'完成',exact:true}).click();await expect(body).toContainText('空间删除后从暂存草稿恢复的新副本');
});
